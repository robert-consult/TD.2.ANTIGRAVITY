function baseLocale(locale: string): string {
  return String(locale || "").trim().toLowerCase().split("-")[0] || "en";
}

export function applyGlossary(locale: string, text: string): string {
  if (!locale || baseLocale(locale) === "en") return text;
  const rules = GLOSSARY[locale.toLowerCase()] ?? GLOSSARY[baseLocale(locale)];
  if (!rules) return text;
  let out = text;
  for (const [from, to] of Object.entries(rules)) {
    if (!from || !to) continue;
    out = out.replaceAll(from, to);
  }
  return out;
}
